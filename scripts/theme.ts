type ZellijFields = Record<string, string>;

function zellijBlock(name: string, fields: ZellijFields): string {
  return `        ${name} {\n${Object.entries(fields)
    .map(([key, value]) => `            ${key} ${rgb(value)}`)
    .join("\n")}\n        }`;
}

