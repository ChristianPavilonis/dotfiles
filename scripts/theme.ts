function hex(value: string): string {
  if (!/^#[0-9a-f]{6}$/i.test(value)) {
    throw new Error(`Invalid color: ${value}`);
  }
  return value.toLowerCase();
}

function rgb(value: string): string {
  const normalized = hex(value).slice(1);
  return [0, 2, 4].map((offset) => Number.parseInt(normalized.slice(offset, offset + 2), 16)).join(" ");
}

function nuString(value: string): string {
  return `'${hex(value)}'`;
}

async function loadThemes(): Promise<Theme[]> {
  const themesRoot = path.join(root, "themes");
  const directories = await readdir(themesRoot, { withFileTypes: true });
  const themes: Theme[] = [];

  for (const directory of directories.filter((entry) => entry.isDirectory()).sort((a, b) => a.name.localeCompare(b.name))) {
    for (const variant of ["dark", "light"] as const) {
      const file = path.join(themesRoot, directory.name, `${variant}.json`);
      try {
        const theme = JSON.parse(await readFile(file, "utf8")) as Theme;
        if (theme.variant !== variant) throw new Error(`${file}: variant does not match filename`);
        for (const value of Object.values(theme.colors)) hex(value);
        for (const value of Object.values(theme.ansi)) hex(value);
        for (const name of ansiOrder) {
          if (!theme.ansi[name]) throw new Error(`${file}: missing ANSI color ${name}`);
        }
        themes.push(theme);
      } catch (error) {
        if ((error as NodeJS.ErrnoException)?.code === "ENOENT") continue;
        throw error;
      }
    }
  }

  if (themes.length === 0) throw new Error("No theme palettes found under themes/*/");
  return themes;
}

async function loadProfile(): Promise<Profile> {
  return JSON.parse(await readFile(path.join(root, "themes", "profile.json"), "utf8")) as Profile;
}

async function writeGenerated(relativePath: string, content: string): Promise<void> {
  const target = path.join(root, relativePath);
  await mkdir(path.dirname(target), { recursive: true });
  const temporary = `${target}.tmp-${process.pid}`;
  await writeFile(temporary, content.endsWith("\n") ? content : `${content}\n`, "utf8");
  await rename(temporary, target);
}

