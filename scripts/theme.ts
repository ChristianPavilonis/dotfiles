function renderZellijThemesBlock(profile: Profile, themes: Theme[]): string {
  const { active, dark, light } = activeThemes(profile, themes);
  const entries = [
    { theme: active, name: "fallout-terminal" },
    { theme: dark, name: "fallout-terminal-dark" },
    { theme: light, name: "fallout-terminal-light" },
  ];

  const nodes = entries.map(({ theme, name }) => {
    const rendered = renderZellij(theme, name);
    const start = rendered.indexOf(`    ${name} {`);
    const end = rendered.lastIndexOf("\n}\n");
    if (start < 0 || end < 0) throw new Error(`Unable to extract generated Zellij theme ${name}`);
    return rendered.slice(start, end);
  });

  return `themes {\n${nodes.join("\n")}\n}`;
}

function replaceZellijThemeBlock(config: string, block: string): string {
  const startMarker = "// BEGIN GENERATED THEMES";
  const endMarker = "// END GENERATED THEMES";
  const start = config.indexOf(startMarker);
  const end = config.indexOf(endMarker);
  if (start < 0 || end < start) throw new Error("Zellij config is missing generated theme markers");
  const before = config.slice(0, start);
  const after = config.slice(end + endMarker.length);
  return `${before}${startMarker}\n${block}\n${endMarker}${after}`;
}

function extractZellijThemeBlock(config: string): string {
  const startMarker = "// BEGIN GENERATED THEMES";
  const endMarker = "// END GENERATED THEMES";
  const start = config.indexOf(startMarker);
  const end = config.indexOf(endMarker);
  if (start < 0 || end < start) throw new Error("Zellij config is missing generated theme markers");
  return config.slice(start + startMarker.length, end).trim();
}

